let currentLocale = 'zh-CN';

export function getLocale() { return currentLocale; }

export async function setLocale(loc) {
  const l = supportedLocales.includes(loc) ? loc : 'zh-CN';
  currentLocale = l;
  const dict = STRINGS[l] || STRINGS['zh-CN'];
  document.documentElement.lang = l.startsWith('zh') ? 'zh-CN' : l;
  // 应用 i18n 到静态文案节点
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });
}

export function t(key) {
  const dict = STRINGS[currentLocale] || STRINGS['zh-CN'];
  return dict[key] || (STRINGS['zh-CN'][key] || key);
}